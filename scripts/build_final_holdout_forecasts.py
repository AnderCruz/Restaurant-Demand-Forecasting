"""Fit development-selected finalists and save their untouched 28-day forecasts."""
from __future__ import annotations

from importlib.metadata import version
from pathlib import Path
import json
import sys

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingRegressor
from sklearn.impute import SimpleImputer
from sklearn.pipeline import make_pipeline

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.backtesting import naive_forecast, seasonal_naive_forecast, recursive_predict
from src.data import TARGETS, load_demand
from src.features import make_calendar_features, make_lag_features
from src.models.prophet_models import future_frame, make_model, prophet_frame
from src.models.statsmodels_models import fit_candidates, forecast_frame

HORIZON = 28


def _row(date, target, model, horizon, prediction, lower=np.nan, upper=np.nan):
    return {"date": date, "restaurant": target, "model": model, "horizon": horizon,
            "prediction": float(prediction), "lower": float(lower), "upper": float(upper)}


def main() -> None:
    np.random.seed(42)
    demand = load_demand(ROOT / "data/raw/clientes_restaurantes.csv")
    demand["Total demand"] = demand[list(TARGETS)].sum(axis=1, min_count=2)
    development, holdout = demand.iloc[:-HORIZON].copy(), demand.iloc[-HORIZON:].copy()
    rows = []

    # Baselines and HistGradientBoosting use only observations before the holdout.
    selection = json.loads((ROOT / "artifacts/models/ml_hyperparameter_selection.json").read_text())["selected_parameters"]
    for target in [*TARGETS, "Total demand"]:
        train = development[target].interpolate(limit_area="inside").dropna()
        future = holdout.index
        for name, prediction in {
            "naive": naive_forecast(train, future),
            "seasonal_naive_7": seasonal_naive_forecast(train, future, period=7),
        }.items():
            for step, (date, value) in enumerate(prediction.items(), start=1):
                rows.append(_row(date, target, f"baseline_{name}", step, value))

        x_train = make_calendar_features(train.index).join(make_lag_features(train))
        valid = x_train.notna().all(axis=1)
        model = make_pipeline(
            SimpleImputer(strategy="median"),
            HistGradientBoostingRegressor(random_state=42, **selection[target]),
        )
        model.fit(x_train.loc[valid], train.loc[valid])

        def build_features(values):
            return make_calendar_features(values.index).join(make_lag_features(values))

        prediction = recursive_predict(model, train, future, build_features, target)
        for step, (date, value) in enumerate(prediction.items(), start=1):
            rows.append(_row(date, target, "hist_gradient_boosting_recursive", step, value))

    # The classical finalists were selected on aligned development folds in report/model_comparison.md.
    for target in ("Chimi & Churri", "Total demand"):
        train = development[target].interpolate(limit_area="inside").dropna()
        model = make_model(seasonality_mode="additive", yearly_seasonality=False)
        model.fit(prophet_frame(train))
        prediction = model.predict(future_frame(model, HORIZON)).tail(HORIZON)
        for step, (_, item) in enumerate(prediction.iterrows(), start=1):
            rows.append(_row(item["ds"], target, "prophet_additive_selected_on_aligned_cv", step,
                             item["yhat"], item["yhat_lower"], item["yhat_upper"]))

    target = "Assa Frão"
    train = development[target].interpolate(limit_area="inside").dropna()
    fitted = fit_candidates(train)
    result = fitted["SARIMAX_weekly_AIC"]
    if isinstance(result, Exception):
        raise RuntimeError("The development-selected weekly SARIMAX candidate could not be fitted") from result
    prediction = forecast_frame(result, HORIZON, holdout.index)
    for step, (date, item) in enumerate(prediction.iterrows(), start=1):
        rows.append(_row(date, target, "statsmodels_SARIMAX_weekly_AIC_selected_on_aligned_cv", step,
                         item["yhat"], item["yhat_lower"], item["yhat_upper"]))

    # Neural forecasts were generated by notebook 08 using its development-fold architecture selection.
    neural_path = ROOT / "artifacts/forecasts/deep_learning_holdout_forecasts.csv"
    metadata_path = ROOT / "artifacts/models/deep_learning_metadata.json"
    if neural_path.exists() and metadata_path.exists():
        metadata = json.loads(metadata_path.read_text())
        expected_dates = [str(holdout.index.min().date()), str(holdout.index.max().date())]
        if (
            metadata.get("final_holdout_period") == expected_dates
            and metadata.get("training_cutoff") == str(development.index.max().date())
            and metadata.get("forecast_horizon_days") == HORIZON
        ):
            neural = pd.read_csv(neural_path, parse_dates=["date"])
            for target, info in metadata.get("selected_models", {}).items():
                model_name = f"tensorflow_{info['architecture']}"
                part = neural[(neural["restaurant"] == target) & (neural["model"] == model_name)]
                part = part.sort_values("date")
                if len(part) != HORIZON or part["date"].tolist() != list(holdout.index):
                    print(f"Skipping incomplete or misaligned neural forecast for {target}.")
                    continue
                for item in part.to_dict("records"):
                    rows.append(_row(item["date"], target, model_name, item["horizon"],
                                     item["prediction"], item.get("lower", np.nan), item.get("upper", np.nan)))
        else:
            print("Skipping saved neural holdout forecasts because their metadata does not match this holdout.")

    output = pd.DataFrame(rows).sort_values(["restaurant", "model", "horizon"])
    out_path = ROOT / "artifacts/forecasts/final_holdout_forecasts.csv"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    output.to_csv(out_path, index=False)
    metadata = {
        "training_cutoff": str(development.index.max().date()),
        "holdout_period": [str(holdout.index.min().date()), str(holdout.index.max().date())],
        "horizon_days": HORIZON,
        "selection": "Classical finalists and HistGradientBoosting parameters selected on development folds; neural architecture selected in notebook 08 development folds. Baselines are included.",
        "package_versions": {name: version(name) for name in ("pandas", "scikit-learn", "statsmodels", "prophet")},
        "forecasts": str(out_path.relative_to(ROOT)),
        "intervals": "Available for Prophet and Statsmodels forecasts; not estimated for baselines, HistGradientBoosting, or neural forecasts.",
    }
    (ROOT / "artifacts/models/final_holdout_metadata.json").write_text(json.dumps(metadata, indent=2))
    print(f"Saved {len(output)} holdout forecasts to {out_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
